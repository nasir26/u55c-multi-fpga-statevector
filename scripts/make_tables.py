# ---------------------------------------------------------------------------------------------- correctness
def tab_correctness(recs):
    rows = [r for r in recs if "metrics" in r]
    if not rows:
        write("tab_correctness.tex", pending("correctness table (E1, E7)") + "\n")
        return
    by = defaultdict(list)
    for r in rows:
        by[(r["circuit"], r.get("init", "zero"))].append(r)
    worst_all = 0.0
    lines = []
    for (c, init), rs in sorted(by.items()):
        ns = sorted({r["n"] for r in rs})
        w = max(rs, key=lambda r: r["metrics"]["max_abs_err"])
        worst_all = max(worst_all, w["metrics"]["max_abs_err"])
        lines.append(f"{c.replace('_', ' ')} & {init} & {ns[0]} to {ns[-1]} & {len(rs)} & "
                     f"{sci(max(r['metrics']['one_minus_F'] for r in rs))} & {sci(w['metrics']['max_abs_err'])} & "
                     f"{sci(max(r['metrics']['l2_err'] for r in rs))} \\\\\n")
    write("tab_correctness.tex", "\\begin{tabular}{@{}llcrrrr@{}}\n\\toprule\nCircuit & Input & $n$ & Instances & "
          "max $1-F$ & max $|\\Delta\\alpha|$ & max $\\ell_2$ \\\\\n\\midrule\n" + "".join(lines) + "\\bottomrule\n\\end{tabular}\n")
    macro("NumWorstMaxAbsErr", sci(worst_all))
    macro("NumCorrectnessInstances", str(len(rows)))
    macro("NumWorstOneMinusF", sci(max(r["metrics"]["one_minus_F"] for r in rows)))
    macro("NumCorrectnessExact", str(sum(1 for r in rows if r["metrics"]["max_abs_err"] == 0)))
    ns = sorted({r["n"] for r in rows})
    macro("NumCorrectnessNmin", str(ns[0])); macro("NumCorrectnessNmax", str(ns[-1]))
    macro("NumCorrectnessHaar", str(sum(1 for r in rows if r.get("init") == "haar")))


# ---------------------------------------------------------------------------------------------- platform and resources
def util(build):
    import glob as g
    rep = (g.glob(os.path.join(ROOT, "builds", build, "reports", "**", "impl_1_full_util_routed.rpt"), recursive=True) or [None])[0]
    if not rep:
        return None
    out = {}
    for line in open(rep):
        for key, pat in (("lut", r"^\| CLB LUTs\s+\|"), ("ff", r"^\| CLB Registers\s+\|"), ("bram", r"^\| Block RAM Tile\s+\|"),
                         ("uram", r"^\| URAM\s+\|"), ("dsp", r"^\| DSPs\s+\|")):
            if re.match(pat, line) and key not in out:
                c = [x.strip() for x in line.split("|")]
                out[key] = (float(c[2]), float(c[5]), float(c[6]))     # used, available, percent
    return out


