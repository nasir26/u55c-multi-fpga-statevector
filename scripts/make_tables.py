#!/usr/bin/env python3
"""Generates every table body and number macro of the revised manuscript from results/raw (no hand typed numbers).

Author: Nasir Ali, C-DAC Noida.

Inputs : results/raw/**/*.json written by the experiment drivers (records with warm up repetitions flagged),
         results/hardware_manifest.json, builds/*/reports (resources).
Outputs: paper/generated/macros.tex and paper/generated/tab_*.tex.
Statistics: median over the timed repetitions (warm up excluded), interquartile range in brackets where shown.
usage: make_tables.py [--allow-missing]   (missing inputs leave \\PENDING{...} markers instead of failing)
"""
import glob, json, os, re, sys
from collections import defaultdict
import numpy as np

ROOT = os.path.abspath(os.path.join(os.path.dirname(os.path.abspath(__file__)), ".."))
RAW = os.path.join(ROOT, "results", "raw")
GEN = os.path.join(ROOT, "paper", "generated")
ALLOW_MISSING = "--allow-missing" in sys.argv
MACROS = {}


def macro(name, value):
    assert re.fullmatch(r"[A-Za-z]+", name), name
    MACROS[name] = value


def pending(what):
    if not ALLOW_MISSING:
        raise SystemExit(f"missing input: {what} (use --allow-missing for a draft build)")
    return r"\PENDING{" + what + "}"


def fmt_t(x):
    """Seconds with three significant figures."""
    if x is None or not np.isfinite(x):
        return "n/a"
    return f"{x:.3g}"


def fmt_e(x):
    return "0" if x == 0 else f"{x:.2e}".replace("e-0", "e-").replace("e+0", "e")


def sci(x):
    """LaTeX scientific notation a times 10^b with three significant figures."""
    if x == 0:
        return "0"
    m, e = f"{x:.2e}".split("e")
    return f"${m}\\times 10^{{{int(e)}}}$"


def load(pattern):
    recs, metas = [], []
    for f in sorted(glob.glob(os.path.join(RAW, pattern), recursive=True)):
        d = json.load(open(f))
        if d.get("meta", {}).get("mock"):
            raise SystemExit(f"mock data found in results: {f}")
        metas.append((f, d.get("meta", {})))
        m = d.get("meta", {})
        for r in d.get("records", []):
            r["_file"] = os.path.relpath(f, ROOT)
            r.setdefault("design", "baseline" if "baseline" in m.get("design", "") else "engine")
            r.setdefault("pin_cores", m.get("pin_cores", 0))
            recs.append(r)
    return recs, metas


def med_iqr(vals):
    v = np.asarray(vals, dtype=float)
    return float(np.median(v)), float(np.percentile(v, 75) - np.percentile(v, 25))


def group(recs, keys, field):
    g = defaultdict(list)
    for r in recs:
        if r.get("warmup"):
            continue
        k = tuple(r[x] for x in keys)
        g[k].append(field(r))
    return g


def write(name, body):
    os.makedirs(GEN, exist_ok=True)
    if name.startswith("tab_") and "tabular" not in body:   # sn-jnl sets the caption with the tabular
        body = "\\begin{tabular}{@{}l@{}}\n" + body.strip() + "\n\\end{tabular}\n"
    with open(os.path.join(GEN, name), "w") as f:
        f.write("% generated by scripts/make_tables.py, do not edit\n" + body)


